export function getTranslation(key, lang = 'en-US') {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS['en-US'];
  return dict[key] || TRANSLATIONS['en-US'][key] || key;
}

export function getActiveCurrency(langOrLocale) {
  // 1. Primary priority: Always check active delivery location currency
  try {
    const savedLoc = localStorage.getItem('voice_cart_location');
    if (savedLoc) {
      const parsed = JSON.parse(savedLoc);
      if (parsed) {
        if (parsed.currencyLocale && CURRENCIES[parsed.currencyLocale]) {
          return CURRENCIES[parsed.currencyLocale];
        }
        if (parsed.currency) {
          const match = Object.values(CURRENCIES).find(c => c.code === parsed.currency);
          if (match) return match;
        }
        if (parsed.countryCode) {
          const countryMap = {
            'US': 'en-US', 'IN': 'hi-IN', 'GB': 'en-GB', 'DE': 'de-DE',
            'FR': 'fr-FR', 'CA': 'en-CA', 'AU': 'en-AU', 'JP': 'ja-JP',
            'AE': 'ar-AE', 'SG': 'en-SG', 'BR': 'pt-BR', 'CN': 'zh-CN',
            'KR': 'ko-KR', 'SA': 'ar-SA', 'RU': 'ru-RU', 'IT': 'it-IT',
            'ES': 'es-ES', 'NL': 'nl-NL'
          };
          const locKey = countryMap[parsed.countryCode];
          if (locKey && CURRENCIES[locKey]) return CURRENCIES[locKey];
        }
      }
    }
  } catch (e) {}

  // 2. Secondary priority: Explicit currency/locale parameter
  if (langOrLocale) {
    if (CURRENCIES[langOrLocale]) return CURRENCIES[langOrLocale];
    const match = Object.values(CURRENCIES).find(c => c.code === langOrLocale);
    if (match) return match;
  }

  // 3. Fallback to voice_cart_language
  try {
    const savedLang = localStorage.getItem('voice_cart_language');
    if (savedLang) {
      const parsedLang = JSON.parse(savedLang);
      if (CURRENCIES[parsedLang]) return CURRENCIES[parsedLang];
    }
  } catch (e) {}

  return CURRENCIES['en-US'];
}

export function formatPrice(amountUSD, langOrLocale) {
  const curr = getActiveCurrency(langOrLocale);
  const converted = amountUSD * curr.rate;
  const decimals = curr.decimals !== undefined ? curr.decimals : 2;
  const formattedVal = converted.toLocaleString(undefined, {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals
  });

  if (curr.position === 'prefix') {
    return `${curr.symbol}${formattedVal}`;
  } else {
    return `${formattedVal} ${curr.symbol}`;
  }
}

